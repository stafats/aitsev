"""Export an approved mapping as a standalone Python script the user owns and can edit."""

from __future__ import annotations

import json
import re
from typing import Any

from aitsev.integrations.mapping import FieldMapping
from aitsev.integrations.schema import EntityDef

_TEMPLATE = '''"""__TITLE__

Generated by Aitsev from mapping __MAPPING_ID__ (version __VERSION__).
Moves __SOURCE_ENTITY__ records from __SOURCE_URL__ to __TARGET_ENTITY__ at __TARGET_URL__.

Requirements: Python 3.10+ and httpx  (pip install httpx)
Credentials come from environment variables, never from this file:
    SOURCE_AUTH_HEADER   e.g. "Authorization: Bearer <token>"  (optional)
    TARGET_AUTH_HEADER   e.g. "X-API-Key: <key>"               (optional)

Usage:
    python __FILENAME__ --dry-run        # transform and validate only
    python __FILENAME__ --limit 100      # write the first 100 records
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime

import httpx

SOURCE_URL = __SOURCE_URL_LIT__
SOURCE_LIST_PATH = __SOURCE_LIST_LIT__
SOURCE_RECORDS_KEY = __RECORDS_KEY_LIT__
TARGET_URL = __TARGET_URL_LIT__
TARGET_CREATE_PATH = __TARGET_CREATE_LIT__
PAGINATION = json.loads(__PAGINATION_LIT__)
FIELDS = json.loads(__FIELDS_LIT__)
REQUIRED = __REQUIRED_LIT__

TRUE = {"true", "1", "yes", "y", "t", "on"}
FALSE = {"false", "0", "no", "n", "f", "off"}


def read_path(record, path):
    current = record
    for part in path.split("."):
        if not isinstance(current, dict):
            return None
        current = current.get(part)
    return current


def parse_dt(value, fmt):
    text = str(value).strip()
    return datetime.strptime(text, fmt) if fmt else datetime.fromisoformat(text.replace("Z", "+00:00"))


def apply_step(step, value):
    op = step["op"]
    if op == "default":
        return step["value"] if value is None or (isinstance(value, str) and not value.strip()) else value
    if op == "map_values":
        key = "" if value is None else str(value)
        if key in step["values"]:
            return step["values"][key]
        if step.get("strict"):
            raise ValueError(f"no mapping for {key!r}")
        return step.get("default")
    if value is None:
        return None
    if op == "trim":
        return value.strip() if isinstance(value, str) else value
    if op == "lower":
        return str(value).lower()
    if op == "upper":
        return str(value).upper()
    if op == "to_string":
        return str(value)
    if op == "prefix":
        return f"{step['text']}{value}"
    if op == "truncate":
        return str(value)[: step["length"]]
    if op == "split":
        parts = str(value).split(step.get("sep", " "))
        index = step.get("index", 0)
        return parts[index].strip() if -len(parts) <= index < len(parts) else None
    if op == "to_int":
        number = float(str(value).replace(",", "")) if not isinstance(value, bool) else int(value)
        if number != int(number):
            raise ValueError(f"not a whole number: {value!r}")
        return int(number)
    if op == "to_float":
        return float(str(value).replace(",", ""))
    if op == "to_bool":
        if isinstance(value, bool):
            return value
        text = str(value).strip().lower()
        if text in TRUE:
            return True
        if text in FALSE:
            return False
        raise ValueError(f"not a yes/no value: {value!r}")
    if op == "to_date":
        return parse_dt(value, step.get("input_format")).date().isoformat()
    if op == "to_datetime":
        return parse_dt(value, step.get("input_format")).isoformat()
    raise ValueError(f"unknown step {op}")


def transform(record):
    out, errors = {}, []
    for field in FIELDS:
        if field.get("constant") is not None:
            value = field["constant"]
        elif field.get("sources"):
            parts = [read_path(record, s) for s in field["sources"]]
            text = [str(p).strip() for p in parts if p is not None and str(p).strip()]
            value = field.get("separator", " ").join(text) if text else None
        else:
            value = read_path(record, field["source"])
        try:
            for step in field.get("steps", []):
                value = apply_step(step, value)
        except (ValueError, TypeError) as exc:
            errors.append(f"{field['target']}: {exc}")
            continue
        if value is not None:
            out[field["target"]] = value
    for name in REQUIRED:
        if out.get(name) in (None, ""):
            errors.append(f"{name}: required value is missing")
    return out, errors


def headers(env_name):
    raw = os.environ.get(env_name, "")
    name, sep, value = raw.partition(":")
    base = {"Accept": "application/json"}
    if sep:
        base[name.strip()] = value.strip()
    return base


def records(client, limit):
    style = PAGINATION.get("style", "none")
    size = PAGINATION.get("page_size", 100)
    page, offset, cursor, url, seen = PAGINATION.get("first_page", 1), 0, None, SOURCE_LIST_PATH, 0
    while True:
        params = {}
        if style == "page":
            params = {PAGINATION.get("page_param", "page"): page, PAGINATION.get("size_param", "per_page"): size}
        elif style == "offset":
            params = {PAGINATION.get("offset_param", "offset"): offset, PAGINATION.get("limit_param", "limit"): size}
        elif style == "cursor" and cursor:
            params = {PAGINATION.get("cursor_param", "cursor"): cursor}
        response = client.get(url, params=params or None)
        response.raise_for_status()
        body = response.json()
        if SOURCE_RECORDS_KEY:
            batch = read_path(body, SOURCE_RECORDS_KEY)
        elif isinstance(body, list):
            batch = body
        else:
            batch = next((body[k] for k in ("value", "data", "items", "results", "records") if k in body), [])
        for record in batch:
            yield record
            seen += 1
            if limit and seen >= limit:
                return
        if style == "none" or not batch:
            return
        if style == "page":
            page += 1
            if len(batch) < size:
                return
        elif style == "offset":
            offset += len(batch)
            if len(batch) < size:
                return
        elif style == "cursor":
            cursor = read_path(body, PAGINATION.get("cursor_path", "next_cursor"))
            if not cursor:
                return
        elif style == "odata":
            url = body.get("@odata.nextLink")
            if not url:
                return


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true", help="validate only, write nothing")
    parser.add_argument("--limit", type=int, default=0, help="stop after this many records")
    args = parser.parse_args()
    stats = {"read": 0, "valid": 0, "invalid": 0, "written": 0, "write_failed": 0}
    with httpx.Client(base_url=SOURCE_URL, headers=headers("SOURCE_AUTH_HEADER"), timeout=60) as src, \\
            httpx.Client(base_url=TARGET_URL, headers=headers("TARGET_AUTH_HEADER"), timeout=60) as dst:
        for record in records(src, args.limit):
            stats["read"] += 1
            out, errors = transform(record)
            if errors:
                stats["invalid"] += 1
                print(json.dumps({"record": stats["read"], "errors": errors}), file=sys.stderr)
                continue
            stats["valid"] += 1
            if args.dry_run:
                continue
            response = dst.post(TARGET_CREATE_PATH, json=out)
            if response.status_code >= 400:
                stats["write_failed"] += 1
                print(json.dumps({"record": stats["read"], "status": response.status_code}), file=sys.stderr)
            else:
                stats["written"] += 1
    print(json.dumps(stats))
    return 1 if stats["invalid"] or stats["write_failed"] else 0


if __name__ == "__main__":
    sys.exit(main())
'''


def script_name(source_entity: str, target_entity: str) -> str:
    raw = f"migrate_{source_entity}_to_{target_entity}".lower()
    return re.sub(r"[^a-z0-9_]+", "_", raw).strip("_") + ".py"


def export_script(
    *,
    mapping_id: str,
    version: int,
    source_url: str,
    source: EntityDef,
    target_url: str,
    target: EntityDef,
    pagination: dict[str, Any],
    fields: list[FieldMapping],
) -> tuple[str, str]:
    """Return (file name, script text). Only approved mappings are exported."""
    approved = [
        f.model_dump(mode="json", exclude={"confidence", "method", "status", "reason"})
        for f in fields
        if f.status == "approved" and f.has_input
    ]
    required = [f.name for f in target.fields if f.required and not f.read_only]
    filename = script_name(source.name, target.name)
    replacements = {
        "__TITLE__": f"Migrate {source.name} to {target.name}",
        "__MAPPING_ID__": mapping_id,
        "__VERSION__": str(version),
        "__SOURCE_ENTITY__": source.name,
        "__TARGET_ENTITY__": target.name,
        "__SOURCE_URL__": source_url,
        "__TARGET_URL__": target_url,
        "__FILENAME__": filename,
        "__SOURCE_URL_LIT__": repr(source_url),
        "__SOURCE_LIST_LIT__": repr(source.list_path or "/"),
        "__RECORDS_KEY_LIT__": repr(source.records_key),
        "__TARGET_URL_LIT__": repr(target_url),
        "__TARGET_CREATE_LIT__": repr(target.create_path or "/"),
        "__PAGINATION_LIT__": repr(json.dumps(pagination)),
        "__FIELDS_LIT__": repr(json.dumps(approved, indent=1)),
        "__REQUIRED_LIT__": repr(required),
    }
    text = _TEMPLATE
    for key, value in replacements.items():
        text = text.replace(
            key, value.replace('"""', "'''") if not key.endswith("_LIT__") else value
        )
    return filename, text
